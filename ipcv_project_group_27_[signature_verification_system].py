# ── 4-A  Core pre-processor ──────────────────────────────────────────────────
def preprocess_signature(img_bgr, return_steps=False):
    """
    Full image-processing pipeline for one signature image.

    Steps
    -----
    1. Resize to IMG_SIZE
    2. Grayscale conversion
    3. CLAHE  (contrast-limited adaptive histogram equalisation)
    4. Gaussian blur  (noise suppression)
    5. Adaptive thresholding  (local illumination robustness)
    6. Morphological closing  (gap repair)
    7. Largest-contour crop   (remove background / margin noise)
    8. Skeletonisation         (stroke-width normalisation)
    9. Feature extraction: Hu moments + LBP histogram

    Returns
    -------
    skeleton  : (128,128) uint8  –– normalised binary image for CNN
    features  : 1-D float array   –– hand-crafted descriptor
    steps     : dict[str → ndarray]  (only when return_steps=True)
    """
    steps = {}

    # ── 1. Resize ─────────────────────────────────────────────────────────
    img = cv2.resize(img_bgr, IMG_SIZE)
    if return_steps: steps["1 · Original (resized)"] = img.copy()

    # ── 2. Grayscale ──────────────────────────────────────────────────────
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    if return_steps: steps["2 · Grayscale"] = gray

    # ── 3. CLAHE – contrast enhancement ───────────────────────────────────
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
    enhanced = clahe.apply(gray)
    if return_steps: steps["3 · CLAHE enhanced"] = enhanced

    # ── 4. Gaussian blur ──────────────────────────────────────────────────
    blur = cv2.GaussianBlur(enhanced, (5, 5), 0)
    if return_steps: steps["4 · Gaussian blur"] = blur

    # ── 5. Adaptive threshold (ink → white, background → black) ───────────
    thresh = cv2.adaptiveThreshold(
        blur, 255,
        cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
        cv2.THRESH_BINARY_INV,
        blockSize=11, C=2
    )
    if return_steps: steps["5 · Adaptive threshold"] = thresh

    # ── 6. Morphological closing  (bridge small gaps in ink strokes) ───────
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (3, 3))
    morph  = cv2.morphologyEx(thresh, cv2.MORPH_CLOSE, kernel, iterations=2)
    if return_steps: steps["6 · Morphological closing"] = morph

    # ── 7. Largest-contour crop  (eliminate stray noise blobs) ────────────
    contours, _ = cv2.findContours(morph, cv2.RETR_EXTERNAL,
                                   cv2.CHAIN_APPROX_SIMPLE)
    clean = np.zeros_like(morph)
    if contours:
        # keep only contours > 0.5 % of image area
        min_area = 0.005 * IMG_SIZE[0] * IMG_SIZE[1]
        for c in contours:
            if cv2.contourArea(c) >= min_area:
                cv2.drawContours(clean, [c], -1, 255, thickness=cv2.FILLED)
    if return_steps: steps["7 · Noise removal"] = clean

    # ── 8. Skeletonisation  (reduce to 1-pixel-wide strokes) ──────────────
    skel_bool = skeletonize(clean // 255)
    skeleton  = (skel_bool * 255).astype(np.uint8)
    if return_steps: steps["8 · Skeleton"] = skeleton

    # ── 9. Feature extraction ─────────────────────────────────────────────
    # 9-a  Hu moments (shape invariants)
    moments = cv2.moments(skeleton)
    hu      = cv2.HuMoments(moments).flatten()
    hu_log  = -np.sign(hu) * np.log10(np.abs(hu) + 1e-10)

    # 9-b  LBP texture histogram (uniform, radius=1, 8 neighbours)
    lbp      = local_binary_pattern(skeleton, P=8, R=1, method='uniform')
    lbp_hist, _ = np.histogram(lbp.ravel(), bins=10, range=(0, 10),
                                density=True)

    # 9-c  Stroke density  (fraction of white pixels)
    density = np.sum(skeleton > 0) / skeleton.size

    features = np.concatenate([hu_log, lbp_hist, [density]])   # (18,)

    if return_steps:
        return skeleton, features, steps
    return skeleton, features


