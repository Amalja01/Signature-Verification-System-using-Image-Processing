def verify(img1_bgr, img2_bgr):

    sk1, feat1, steps1 = preprocess_signature(img1_bgr, return_steps=True)
    sk2, feat2, steps2 = preprocess_signature(img2_bgr, return_steps=True)

    # CNN distance
