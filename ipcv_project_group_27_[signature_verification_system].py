def build_encoder(input_shape=(128, 128, 1), embedding_dim=128):
    """
    Shared CNN encoder  –  takes a single signature image → embedding vector.

    Architecture
    ────────────
    Block 1 : Conv(32) → BN → ReLU → Conv(32) → BN → ReLU → MaxPool → Dropout
    Block 2 : Conv(64) → BN → ReLU → Conv(64) → BN → ReLU → MaxPool → Dropout
    Block 3 : Conv(128)→ BN → ReLU → GlobalAvgPool
    Head    : Dense(256) → Dense(embedding_dim)
    """
    inp = Input(shape=input_shape, name="img_input")
    x   = inp

    # Block 1
    x = Conv2D(32, (3,3), padding='same', activation='relu')(x)
    x = BatchNormalization()(x)
    x = Conv2D(32, (3,3), padding='same', activation='relu')(x)
    x = BatchNormalization()(x)
    x = MaxPooling2D()(x)
    x = Dropout(0.25)(x)

    # Block 2
    x = Conv2D(64, (3,3), padding='same', activation='relu')(x)
    x = BatchNormalization()(x)
    x = Conv2D(64, (3,3), padding='same', activation='relu')(x)
    x = BatchNormalization()(x)
    x = MaxPooling2D()(x)
    x = Dropout(0.25)(x)

    # Block 3
    x = Conv2D(128, (3,3), padding='same', activation='relu')(x)
    x = BatchNormalization()(x)
    x = GlobalAveragePooling2D()(x)

    # Embedding head
    x = Dense(256, activation='relu')(x)
    x = Dropout(0.4)(x)
    embedding = Dense(embedding_dim, activation='relu', name="embedding")(x)

    return Model(inp, embedding, name="encoder")


def euclidean_distance(vects):
    """L2 distance between two embedding vectors."""
    x, y = vects
    return K.sqrt(K.sum(K.square(x - y), axis=1, keepdims=True) + K.epsilon())


def contrastive_loss(y_true, y_pred, margin=1.0):
    """
    Contrastive loss  (LeCun et al.)
    Pulls genuine pairs together, pushes forgery pairs apart.
    y_true = 1  →  genuine   →  minimise distance
    y_true = 0  →  forgery   →  maximise distance (up to margin)
    """
    sq_dist   = K.square(y_pred)
    margin_sq = K.square(K.maximum(margin - y_pred, 0))
    return K.mean(y_true * sq_dist + (1 - y_true) * margin_sq)


