MAX_SIGNERS = None

def load_signer(signer_id):
    """Return list of (skeleton, features) for one signer."""
    folder = os.path.join(DATASET_ROOT, signer_id)
    items  = []
    for fname in sorted(os.listdir(folder)):
        if not fname.lower().endswith(('.jpg','.jpeg','.png')):
            continue
        img = cv2.imread(os.path.join(folder, fname))
        if img is None:
            continue
        sk, feat = preprocess_signature(img)
        items.append((sk, feat))
    return items


def build_dataset(signer_ids, max_pairs_per_signer=10):
    """
    Pair strategy
    ─────────────
    Genuine  (label=1) : two different genuine signatures of the same person
    Forgery  (label=0) : one genuine + one forged of the same person
    """
    X1, X2, labels = [], [], []

    ids = signer_ids if MAX_SIGNERS is None else signer_ids[:MAX_SIGNERS]

    for sid in tqdm(ids, desc="Loading signers"):
        forg_id  = sid + "_forg"
        genuine  = load_signer(sid)
        forgery  = load_signer(forg_id)

        if len(genuine) < 2 or len(forgery) < 1:
            continue

        # ── Positive pairs: shuffle & zip genuine with itself ──────────────
        g_shuffled = genuine[:]
        random.shuffle(g_shuffled)
        pos_limit = min(max_pairs_per_signer, len(genuine) // 2)
        for i in range(pos_limit):
            X1.append(genuine[i][0])
            X2.append(genuine[i + pos_limit][0])
            labels.append(1)

        # ── Negative pairs: genuine vs forged ─────────────────────────────
        neg_limit = min(max_pairs_per_signer, len(genuine), len(forgery))
        fake_idx  = list(range(len(forgery)))
        random.shuffle(fake_idx)
        for i in range(neg_limit):
            X1.append(genuine[i][0])
            X2.append(forgery[fake_idx[i]][0])
            labels.append(0)

    X1 = np.array(X1, dtype=np.float32)[..., np.newaxis] / 255.0
    X2 = np.array(X2, dtype=np.float32)[..., np.newaxis] / 255.0
    labels = np.array(labels, dtype=np.float32)
    return X1, X2, labels


