    t2 = sk2.reshape(1, 128, 128, 1).astype(np.float32) / 255.0
    dist = siamese_model.predict([t1, t2], verbose=0)[0][0]

    similarity_score = float(1 / (1 + dist))

    # SSIM
    ssim_score, _ = ssim(sk1, sk2, full=True)

    # Hu moments
    hu_dist = float(np.linalg.norm(feat1[:7] - feat2[:7]))

    # LBP similarity
    lbp1 = feat1[7:17]
    lbp2 = feat2[7:17]
    lbp1 = lbp1 / (lbp1.sum() + 1e-9)
    lbp2 = lbp2 / (lbp2.sum() + 1e-9)
    bhatt_coeff = float(np.sum(np.sqrt(lbp1 * lbp2)))

    hu_score = np.exp(-hu_dist)   # converts distance → similarity

    combined = (0.4 * similarity_score +
            0.25 * ssim_score +
            0.25 * bhatt_coeff +
            0.1 * hu_score)

    threshold = 0.75

    verdict = "GENUINE" if combined >= threshold else "FORGERY"

    result = {
        "verdict": verdict,
        "cnn_similarity": similarity_score,
        "ssim": ssim_score,
        "hu_distance": hu_dist,
        "lbp_bhattacharyya": bhatt_coeff,
        "combined_score": combined,
        "threshold_used": threshold,
    }

    return result, steps1, steps2

